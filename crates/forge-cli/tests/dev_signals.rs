//! `forge dev` never leaves the application it runs serving on its own: the
//! application leads a process group of its own (so a terminal's Ctrl-C
//! reaches only the CLI, which stops it with a grace period), so whatever
//! ends `forge dev` (SIGINT, SIGTERM, a closed terminal's SIGHUP, SIGQUIT)
//! must stop it first. Before SIGHUP and SIGQUIT were handled, their default
//! action ended `forge dev` at once and the application kept serving.
//!
//! The "application" is a tiny Cargo package that depends on a stand-in
//! `forge` crate, so it builds in seconds; it prints its process id and
//! waits forever.

#![cfg(unix)]

use std::io::{BufRead as _, BufReader};
use std::path::Path;
use std::process::{Child, Command, Stdio};
use std::sync::mpsc;
use std::time::Duration;

use rustix::process::{Pid, Signal, kill_process, test_kill_process};

fn write(path: &Path, content: &str) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("directory");
    }
    std::fs::write(path, content).expect("write");
}

/// A package `forge dev` accepts, whose binary prints `pid=N` and then
/// waits until it is killed.
fn application(root: &Path) {
    write(
        &root.join("Cargo.toml"),
        "[package]\nname = \"orphan_probe\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n\
         [dependencies]\nforge = { path = \"forge\" }\n\n[workspace]\n",
    );
    write(
        &root.join("src/main.rs"),
        "fn main() {\n    println!(\"pid={}\", std::process::id());\n    forge::wait();\n}\n",
    );
    write(
        &root.join("forge/Cargo.toml"),
        "[package]\nname = \"forge\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    );
    // forge dev builds with --locked.
    write(
        &root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n\
         version = 4\n\n[[package]]\nname = \"forge\"\nversion = \"0.1.0\"\n\n\
         [[package]]\nname = \"orphan_probe\"\nversion = \"0.1.0\"\ndependencies = [\n \"forge\",\n]\n",
    );
    // Parks the thread for good: no busy loop and no sleep.
    write(
        &root.join("forge/src/lib.rs"),
        "pub fn wait() {\n    loop {\n        std::thread::park();\n    }\n}\n",
    );
}

/// Starts `forge dev` and returns it with the process id of the application
/// it started.
fn dev(root: &Path) -> (Child, i32) {
    let mut child = Command::new(env!("CARGO_BIN_EXE_forge"))
        .arg("dev")
        .current_dir(root)
        .env(
            "CARGO_TARGET_DIR",
            Path::new(env!("CARGO_TARGET_TMPDIR")).join("dev-signals"),
        )
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("forge dev starts");
    let (lines, received) = mpsc::channel::<String>();
    for stream in [
        child
            .stdout
            .take()
            .map(|out| Box::new(out) as Box<dyn std::io::Read + Send>),
        child
            .stderr
            .take()
            .map(|err| Box::new(err) as Box<dyn std::io::Read + Send>),
    ]
    .into_iter()
    .flatten()
    {
        let lines = lines.clone();
        std::thread::spawn(move || {
            for line in BufReader::new(stream).lines().map_while(Result::ok) {
                let _ = lines.send(line);
            }
        });
    }
    let mut log = String::new();
    while let Ok(line) = received.recv_timeout(Duration::from_secs(300)) {
        if let Some(pid) = line
            .strip_prefix("pid=")
            .and_then(|pid| pid.trim().parse().ok())
        {
            return (child, pid);
        }
        log.push_str(&line);
        log.push('\n');
        if line.contains("build failed") {
            break;
        }
    }
    let _ = child.kill();
    let _ = child.wait();
    panic!("the application did not start:\n{log}");
}

#[test]
fn every_stop_signal_stops_the_application_with_forge_dev() {
    let directory = tempfile::tempdir().expect("temporary directory");
    application(directory.path());
    for signal in [Signal::INT, Signal::TERM, Signal::HUP, Signal::QUIT] {
        let (mut forge_dev, application) = dev(directory.path());
        let application = Pid::from_raw(application).expect("a process id");
        assert!(
            test_kill_process(application).is_ok(),
            "the application runs"
        );

        let pid = i32::try_from(forge_dev.id())
            .ok()
            .and_then(Pid::from_raw)
            .expect("forge dev's process id");
        kill_process(pid, signal).expect("signal forge dev");
        let status = forge_dev.wait().expect("forge dev exits");

        let orphan = test_kill_process(application).is_ok();
        if orphan {
            let _ = kill_process(application, Signal::KILL);
        }
        assert!(
            !orphan,
            "{signal:?} ended forge dev ({status}) and left its application serving"
        );
    }
}
